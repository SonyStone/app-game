import { readPsd, readPsdSource, type PsdNewDocumentContext } from '@app-game/psd';
import { openPsd, type PsdResult } from '@app-game/psd/viewer';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { expect, it } from 'vitest';
import { TILE_SIZE } from './brush';
import type { Layer } from './document';
import type { DocumentRect } from './layersInView';
import { writePsdFile } from './psdFile';
import { TILE_BYTES } from './tilePixels';

const researchRoot = process.env.PSD_TEXT_MIXER_RESEARCH_ROOT;

/** Own GPU-generated Paint operands and hashes of saved native recompositions, with no native artwork copied. */
type ExportFacts = {
  id: string;
  linear: boolean;
  region?: DocumentRect;
  layers: (Omit<Layer, 'tiles'> & { sparse: [number, number, number, number, number, number][] })[];
};

type ExportFixture = ExportFacts & {
  context: Omit<PsdNewDocumentContext, 'profile'>;
  mergedSha256: string;
  width: number;
  height: number;
};

const fixtures: ExportFixture[] = JSON.parse(
  await readFile(new URL('./fixtures/psdExport.json', import.meta.url), 'utf8')
);

// Generated by paint_export_browser.mjs and paint_export_repair_contexts.py in the research evidence directory.
// Each hash is SHA-256 of openPsd(native-recomposed).merged().pixels, independent of the product export renderer.
it.each(fixtures)('matches the native merged RGBA for $id', async (fixture) => {
  const bytes = await replay(fixture, fixture.context);
  const document = value(await openPsd(bytes));
  try {
    const merged = value(document.merged());
    expect(document.info).toMatchObject({
      width: fixture.width,
      height: fixture.height,
      psb: fixture.id === 'psb-wide'
    });
    expect(createHash('sha256').update(merged.pixels).digest('hex')).toBe(fixture.mergedSha256);
    if (fixture.id.endsWith('-opacity')) {
      expect(fixture.layers.at(-1)!.opacity).toBe(0.33333);
      expect((await readPsd(bytes)).layers.at(-1)!.opacity).toBe(85 / 255);
    }
  } finally {
    document.close();
  }
});

/**
 * Replays our own Paint/GPU-generated operands, never a third-party drawing. Generate with
 * evidence/2026-10-26-psd-E-paint-export/paint_export_browser.mjs in photoshop-analysis.
 * Native expectations are the independent Photoshop recompositions listed in measurements.json;
 * repair-checks.json records their zero-difference comparison with the research repair.
 */
it.skipIf(!researchRoot)('matches all 66 native export recompositions and preserves serialized layers', async () => {
  const root = researchRoot!;
  const evidence = join(root, 'evidence/2026-10-26-psd-E-paint-export');
  const checks: { id: string; rgbMismatches: number; alphaMismatches: number }[] = JSON.parse(
    await readFile(join(evidence, 'repair-checks.json'), 'utf8')
  );
  const measurements: { id: string; file: string; recomposed: string }[] = JSON.parse(
    await readFile(join(evidence, 'measurements.json'), 'utf8')
  );
  const contexts: { id: string; context: Omit<PsdNewDocumentContext, 'profile'> }[] = JSON.parse(
    await readFile(join(evidence, 'repair-contexts.json'), 'utf8')
  );
  expect(checks).toHaveLength(66);

  for (const check of checks) {
    expect([check.rgbMismatches, check.alphaMismatches]).toEqual([0, 0]);
    const measurement = measurements.find(({ id }) => id === check.id)!;
    const facts: ExportFacts = JSON.parse(await readFile(join(evidence, `${check.id}.json`), 'utf8'));
    const bytes = await replay(facts, contexts.find(({ id }) => id === check.id)!.context);
    const originalBytes = await readFile(join(root, measurement.file));
    const original = await readPsd(originalBytes);
    expect(await readPsd(bytes), check.id).toEqual(original);
    expect(await readPsdSource(bytes), check.id).toEqual(await readPsdSource(originalBytes));
    const actual = value(await openPsd(bytes));
    try {
      const native = value(await openPsd(await readFile(join(root, measurement.recomposed))));
      try {
        expect(value(actual.merged()), check.id).toEqual(value(native.merged()));
        expect(actual.info, check.id).toMatchObject({ width: original.width, height: original.height });
        if (check.id === 'psb-wide') {
          expect(actual.info).toMatchObject({ width: 30001, height: 2, psb: true });
        }
      } finally {
        native.close();
      }
    } finally {
      actual.close();
    }
  }
}, 60_000);

/** Reconstitutes captured straight pixels into the exact premultiplied tile bytes Paint exported. */
async function replay(facts: ExportFacts, context: ExportFixture['context']): Promise<Uint8Array> {
  const layers = facts.layers.map(({ sparse, ...layer }): Layer => {
    const tiles = new Map<string, Uint8Array>();
    for (const [x, y, r, g, b, a] of sparse) {
      const tx = Math.floor(x / TILE_SIZE);
      const ty = Math.floor(y / TILE_SIZE);
      const key = `${tx},${ty}`;
      const tile = tiles.get(key) ?? new Uint8Array(TILE_BYTES);
      const offset = ((y - ty * TILE_SIZE) * TILE_SIZE + x - tx * TILE_SIZE) * 4;
      tile.set([Math.round(r * a / 255), Math.round(g * a / 255), Math.round(b * a / 255), a], offset);
      tiles.set(key, tile);
    }

    return { ...layer, tiles };
  });
  const profile = new Uint8Array(await readFile(new URL('./assets/sRGB.icc', import.meta.url)));
  const blob = await writePsdFile(
    layers,
    async () => {
      throw new Error('All operands are in memory');
    },
    facts.region,
    facts.linear,
    { ...context, profile }
  );
  return new Uint8Array(await blob.arrayBuffer());
}

/** Makes a failed fixture read/render fail the test with its diagnostic. */
function value<T>(result: PsdResult<T>): T {
  if (!result.ok) {
    throw new Error(result.error.message);
  }

  return result.value;
}
